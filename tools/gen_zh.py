#!/usr/bin/env python3
"""Simplified Chinese: the name table and the pixel font that draws it.

    python3 tools/gen_moves.py      # first: move_names.h carries the ZH attacks
    python3 tools/gen_zh.py         # -> zh_names.h, cjk_font.h

zh_names.h   English display name -> Chinese, sorted by the English bytes, for
             L() in i18n.cpp (Digimon, items, elements, areas, avatars).
cjk_font.h   a 12x12 bitmap for EVERY non-ASCII character the firmware can
             print: the ZH row of i18n.cpp, the ZH attacks in move_names.h and
             zh_names.h. Rendered from Fusion Pixel 12px (SIL OFL 1.1, see
             tools/fonts/), which is drawn on a 12 px grid, so nothing is
             resampled. About 18 bytes a character.

The character set is DERIVED from the strings, never listed by hand. A string
that uses a character the font does not have stops the build here, with the
character named -- not a tofu box on a player's panel.
"""
import os
import re
import sys

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..'))
sys.path.insert(0, HERE)
import zh_names as ZH

FONT = os.path.join(HERE, 'fonts', 'fusion-pixel-12px-proportional-sc.woff2')
CELL = 12          # the glyph grid
BASE_ROW = 4       # Fusion Pixel 12 at size 12 draws its CJK into rows 4..15


def c_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def write_names():
    rows = sorted(ZH.NAMES.items(), key=lambda kv: kv[0].encode())
    out = ['// GENERATED by tools/gen_zh.py from tools/zh_names.py. Do not edit.',
           '#pragma once', '',
           '// English display name -> simplified Chinese, sorted by the English bytes',
           '// (strcmp order) so L() can binary-search it.',
           'struct ZhName { const char *en, *zh; };',
           '#define ZH_NAME_COUNT %d' % len(rows),
           'static const ZhName ZH_NAMES[ZH_NAME_COUNT] = {']
    out += ['  { %s, %s },' % (c_str(k), c_str(v)) for k, v in rows]
    out += ['};', '']
    open(os.path.join(ROOT, 'zh_names.h'), 'w', encoding='utf-8').write('\n'.join(out))
    return len(rows)


def used_chars():
    chars = set()
    for f in ('i18n.cpp', 'move_names.h', 'zh_names.h'):
        txt = open(os.path.join(ROOT, f), encoding='utf-8').read()
        # only inside string literals: a stray symbol in a comment is not printed
        for lit in re.findall(r'"((?:[^"\\]|\\.)*)"', txt):
            chars.update(c for c in lit if ord(c) > 0x7F)
    return sorted(chars)


def load_font():
    from fontTools.ttLib import TTFont   # needs brotli for woff2
    tmp = os.path.join(HERE, 'fonts', '.fusion12.ttf')
    if not os.path.exists(tmp) or os.path.getmtime(tmp) < os.path.getmtime(FONT):
        f = TTFont(FONT)
        f.flavor = None
        f.save(tmp)
    return TTFont(tmp).getBestCmap(), ImageFont.truetype(tmp, CELL)


def glyph(font, ch):
    im = Image.new('L', (CELL, CELL + BASE_ROW), 0)
    ImageDraw.Draw(im).text((0, 0), ch, font=font, fill=255)
    px = im.load()
    for y in range(BASE_ROW):
        for x in range(CELL):
            if px[x, y] > 127:
                raise SystemExit('%r (U+%04X) draws above the 12 px cell' % (ch, ord(ch)))
    bits = bytearray(CELL * CELL // 8)
    for y in range(CELL):
        for x in range(CELL):
            if px[x, y + BASE_ROW] > 127:
                i = y * CELL + x
                bits[i >> 3] |= 0x80 >> (i & 7)
    return bits


def write_font(chars):
    cmap, font = load_font()
    missing = [c for c in chars if ord(c) not in cmap]
    if missing:
        raise SystemExit('the pixel font has no glyph for: %s' % ' '.join(
            '%s(U+%04X)' % (c, ord(c)) for c in missing))
    wide = [c for c in chars if ord(c) > 0xFFFF]
    if wide:
        raise SystemExit('outside the BMP, not supported: %r' % wide)
    out = ['// GENERATED by tools/gen_zh.py from the strings it draws. Do not edit.',
           '// Glyphs: Fusion Pixel 12px (c) TakWolf, SIL Open Font License 1.1 --',
           '// see tools/fonts/fusion-pixel-OFL.txt.',
           '#pragma once', '#include <stdint.h>', '',
           '#define CJK_CELL %d' % CELL,
           '#define CJK_COUNT %d' % len(chars),
           '// sorted code points, for a binary search',
           'static const uint16_t CJK_CODES[CJK_COUNT] = {']
    for i in range(0, len(chars), 12):
        out.append('  ' + ', '.join('0x%04X' % ord(c) for c in chars[i:i + 12]) + ',')
    out += ['};', '// 12x12, row-major, MSB first: 18 bytes a glyph',
            'static const uint8_t CJK_BITS[CJK_COUNT][%d] = {' % (CELL * CELL // 8)]
    for c in chars:
        b = glyph(font, c)
        out.append('  { %s },  // U+%04X' % (','.join(str(v) for v in b), ord(c)))
    out += ['};', '']
    open(os.path.join(ROOT, 'cjk_font.h'), 'w', encoding='utf-8').write('\n'.join(out))


def main():
    n = write_names()
    chars = used_chars()
    write_font(chars)
    print('zh_names.h: %d names; cjk_font.h: %d characters, %.1f KB'
          % (n, len(chars), len(chars) * (2 + CELL * CELL / 8) / 1024))


if __name__ == '__main__':
    main()
