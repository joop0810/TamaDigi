#!/usr/bin/env python3
"""Generates moves.h (attacks + learnsets) and move_names.h from digimon_data.py.

  python3 tools/gen_moves.py

Learnsets are stored CSR-style: one flat LEARN_TBL of (move, level) pairs plus
a LEARN_OFS index, so Digimon n owns LEARN_OFS[n] .. LEARN_OFS[n+1].
"""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
import digimon_data as D
import zh_names as ZH

LANGS = ['ES', 'EN', 'FR', 'DE', 'IT', 'PT', 'ZH']   # must match the firmware's Lang enum


def ident(name):
    """DATA CRUSH -> MV_DATA_CRUSH"""
    return 'MV_' + ''.join(c if c.isalnum() else '_' for c in name).upper()


def localized(m):
    """One name per LANGS entry. The six Latin-script languages come from
    digimon_data.py; Chinese from zh_names.py, and every attack must have one."""
    name, disp = m[0], m[12]
    if name not in ZH.MOVES:
        sys.exit('no Chinese name for attack %s -- add it to tools/zh_names.py' % name)
    latin = D.GENERIC_NAMES[name] if name in D.GENERIC_NAMES else [disp or name] * 6
    return list(latin) + [ZH.MOVES[name]]


def main():
    D.validate()
    seen = set()
    for m in D.MOVES:
        name, el, cat, power, acc, eff, param, mask, stages, tgt, ail, ach, disp = m
        if ident(name) in seen:
            sys.exit('duplicate attack: %s' % name)
        seen.add(ident(name))
        if cat == D.MC_STATUS and power:
            sys.exit('%s: a status move has no power' % name)
        if cat != D.MC_STATUS and not power:
            sys.exit('%s: power 0' % name)
        if (eff == D.EF_STAGE) != bool(mask):
            sys.exit('%s: EF_STAGE and statMask disagree' % name)
        for lang, v in zip(LANGS, localized(m)):
            # display columns: a CJK character is two (see tcols() in i18n.cpp)
            cols = sum(2 if ord(c) > 0x7F else 1 for c in v)
            if (lang != 'ZH' and not v.isascii()) or cols > 23:
                sys.exit('%s: bad localized name %r' % (name, v))
    assert D.MOVES[-1][0] == 'STRUGGLE', 'STRUGGLE stays last: it is the fallback'

    idx = {m[0]: i + 1 for i, m in enumerate(D.MOVES)}
    o = []
    w = o.append
    w('#pragma once\n#include <stdint.h>\n#include "dex.h"\n\n')
    w('// GENERATED by tools/gen_moves.py from tools/digimon_data.py - do not edit\n\n')
    w('// Category. Special attacks use ivAtk/trAtk against the species\' bSpA,\n'
      '// special defence ivDef/trDef against bSpD.\n')
    w('enum : uint8_t { MC_PHYS = 0, MC_SPEC = 1, MC_STATUS = 2 };\n\n')
    w('enum : uint8_t {\n'
      '  EF_NONE = 0,\n'
      '  EF_STAGE,       // statMask + stages on target\n'
      '  EF_RECOIL,      // param = denominator (4 -> 1/4 of damage dealt)\n'
      '  EF_DRAIN,       // param = % of damage dealt healed back\n'
      '  EF_FIXED_LVL,   // damage = attacker level\n'
      '  EF_FIXED,       // param = flat damage\n'
      '  EF_PRIORITY,    // param = priority bracket\n'
      '  EF_NEVER_MISS,  // skips the accuracy roll\n'
      '  EF_MULTI,       // 2-5 hits, power per hit\n'
      '  EF_HEAL,        // param = % of max VIT restored\n'
      '  EF_RECHARGE,    // loses the next turn\n'
      '  EF_CHARGE,      // charges on turn 1\n'
      '};\n\n')
    w('enum : uint8_t { ST_ATK = 1, ST_DEF = 2, ST_SPA = 4, ST_SPD = 8, ST_SPE = 16 };\n')
    w('enum : uint8_t { TG_SELF = 0, TG_FOE = 1 };\n\n')
    w('// Status ailments. Battle-only: they clear when the fight ends.\n'
      'enum : uint8_t {\n'
      '  AIL_NONE = 0, AIL_PARA = 1, AIL_BURN = 2, AIL_POISON = 3,\n'
      '  AIL_SLEEP = 4, AIL_FREEZE = 5, AIL_CONFUSE = 6,\n};\n\n')
    w('struct MoveEntry {\n'
      '  const char *name;\n'
      '  uint8_t type;      // element (PkType)\n'
      '  uint8_t cat;       // MC_*\n'
      '  uint8_t power;\n'
      '  uint8_t acc;       // percent; 0 = cannot miss\n'
      '  uint8_t effect;    // EF_*\n'
      '  int8_t  param;\n'
      '  uint8_t statMask;  // ST_* (EF_STAGE only)\n'
      '  int8_t  stages;\n'
      '  uint8_t target;    // TG_*\n'
      '  uint8_t ailment;   // AIL_*\n'
      '  uint8_t ailChance; // percent\n'
      '};\n\n')
    w('enum MoveId : uint8_t {\n  MV_NONE = 0,\n')
    for m in D.MOVES:
        w('  %s,\n' % ident(m[0]))
    w('};\n#define MOVE_COUNT %d\n\n' % (len(D.MOVES) + 1))

    CAT = {0: 'MC_PHYS', 1: 'MC_SPEC', 2: 'MC_STATUS'}
    EFN = ['EF_NONE', 'EF_STAGE', 'EF_RECOIL', 'EF_DRAIN', 'EF_FIXED_LVL', 'EF_FIXED',
           'EF_PRIORITY', 'EF_NEVER_MISS', 'EF_MULTI', 'EF_HEAL', 'EF_RECHARGE', 'EF_CHARGE']
    AILN = ['AIL_NONE', 'AIL_PARA', 'AIL_BURN', 'AIL_POISON', 'AIL_SLEEP', 'AIL_FREEZE', 'AIL_CONFUSE']

    def maskname(v):
        bits = [n for n, b in (('ST_ATK', 1), ('ST_DEF', 2), ('ST_SPA', 4), ('ST_SPD', 8), ('ST_SPE', 16)) if v & b]
        return ' | '.join(bits) or '0'

    w('static const MoveEntry MOVE_TBL[MOVE_COUNT] = {\n')
    w('  { "-", T_NEUTRAL, MC_STATUS, 0, 0, EF_NONE, 0, 0, 0, TG_SELF, AIL_NONE, 0 },  // 0: unused\n')
    for i, m in enumerate(D.MOVES):
        name, el, cat, power, acc, eff, param, mask, stages, tgt, ail, ach, _d = m
        w('  { "%s", T_%s, %s, %d, %d, %s, %d, %s, %d, %s, %s, %d },  // %d\n'
          % (name, el.upper(), CAT[cat], power, acc, EFN[eff], param, maskname(mask), stages,
             'TG_SELF' if tgt == D.TG_SELF else 'TG_FOE', AILN[ail], ach, i + 1))
    w('};\n\n')

    w('// Learnsets, CSR: Digimon n owns LEARN_TBL[LEARN_OFS[n] .. LEARN_OFS[n + 1]).\n'
      '// Every entry carries a real level (there are no TMs).\n')
    w('struct LearnEntry { uint8_t move; uint8_t level; };\n\n')
    flat, ofs = [], [0, 0]
    for n in range(1, len(D.ROSTER) + 1):
        for mv, lv in D.learnset(n):
            flat.append((idx[mv], lv))
        ofs.append(len(flat))
    w('static const LearnEntry LEARN_TBL[%d] = {\n' % len(flat))
    for i in range(0, len(flat), 6):
        w('  ' + ' '.join('{ %3d, %3d },' % e for e in flat[i:i + 6]) + '\n')
    w('};\n\n')
    w('static const uint16_t LEARN_OFS[DEX_COUNT + 2] = {\n')
    for i in range(0, len(ofs), 12):
        w('  ' + ' '.join('%5d,' % v for v in ofs[i:i + 12]) + '\n')
    w('};\n\n')
    w('static inline uint8_t learnCount(int16_t dex) {\n'
      '  if (dex < 1 || dex > DEX_COUNT) return 0;\n'
      '  return (uint8_t)(LEARN_OFS[dex + 1] - LEARN_OFS[dex]);\n'
      '}\n\n'
      'static inline uint8_t learnMove(int16_t dex, uint8_t i) {\n'
      '  if (i >= learnCount(dex)) return MV_STRUGGLE;\n'
      '  return LEARN_TBL[LEARN_OFS[dex] + i].move;\n'
      '}\n\n'
      'static inline uint8_t learnLevel(int16_t dex, uint8_t i) {\n'
      '  if (i >= learnCount(dex)) return 0;\n'
      '  return LEARN_TBL[LEARN_OFS[dex] + i].level;\n'
      '}\n')
    root = os.path.join(os.path.dirname(__file__), '..')
    open(os.path.join(root, 'moves.h'), 'w', encoding='utf-8').write(''.join(o))

    def cstr(v):
        return v.replace('\\', '\\\\').replace('"', '\\"')
    n = ['#pragma once\n#include <stdint.h>\n#include "moves.h"\n\n',
         '// GENERATED by tools/gen_moves.py from tools/digimon_data.py - do not edit\n\n',
         '#define MOVE_NAME_LANG_COUNT %d\n' % len(LANGS),
         'static const char *const MOVE_NAME_TBL[MOVE_NAME_LANG_COUNT][MOVE_COUNT] = {\n']
    for li, lang in enumerate(LANGS):
        n.append('  {  // %s\n    "-",  // 0 MV_NONE\n' % lang)
        for i, m in enumerate(D.MOVES, 1):
            n.append('    "%s",  // %d %s\n' % (cstr(localized(m)[li]), i, ident(m[0])))
        n.append('  },\n')
    n.append('};\n')
    open(os.path.join(root, 'move_names.h'), 'w', encoding='utf-8').write(''.join(n))
    print('attacks: %d, learnset rows: %d' % (len(D.MOVES), len(flat)))


if __name__ == '__main__':
    main()
